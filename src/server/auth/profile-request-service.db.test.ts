describe("021 AC-33: a request logs no PIN, digest, hash, key or username", () => {
  it("AC-33: nothing written to the console by a request carries its PIN, digest, hash, account key or username", async () => {
    const spies = (["log", "info", "warn", "error"] as const).map((method) =>
      vi.spyOn(console, method).mockImplementation(() => {}),
    );
    const typed = request();

    expect(await requestProfile(typed, knownDevice())).toEqual({ outcome: "SENT" });
    // A refused one too: the pepper missing.
    vi.stubEnv("PIN_PEPPER", "");
    const refused = request();
    expect(await requestProfile(refused, knownDevice())).toEqual({ outcome: "UNAVAILABLE" });
    vi.unstubAllEnvs();

    const row = await db.user.findFirstOrThrow({ where: { requestedUsername: typed.username } });
    const output = spies
      .flatMap((spy) => spy.mock.calls.flat())
      .map(String)
      .join("\n");
    for (const secret of [
      typed.pin,
      pinDigest(typed.pin),
      row.pinHash ?? "",
      accountKey(typed.username),
      typed.username,
      refused.pin,
      refused.username,
    ]) {
      expect(secret).not.toBe("");
      expect(output).not.toContain(secret);
    }
  });
});
